        dueDate: String?,
        sourceSegmentIDs: [String],
        confidence: Double
    ) {
        self.description = description
        self.owner = owner
        self.dueDate = dueDate
        self.sourceSegmentIDs = sourceSegmentIDs
        self.confidence = confidence
    }
}

